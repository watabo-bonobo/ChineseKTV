// vendor/hanzi-map.js を作り直すためのスクリプト（普段は使いません）。
// リポジトリのルートで実行します。
//
//   npm install --no-save opencc-js
//   node tools/build-hanzi-map.mjs
//
// OpenCC の文字単位の辞書から、次の 2 つの対応表を作ります。
//   T2S  : 繁体字 → 簡体字（ピンインの判定と「簡体字で表示」に使用）
//   JP2T : 日本の新字体 → 繁体字（日本の漢字で入力された曲名を中国語に直すのに使用）
// どちらも 1 文字 → 1 文字の対応だけを残すので、文字の位置がずれません。

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const base = join(process.cwd(), 'node_modules/opencc-js/dist/esm-lib/dict');
const load = async (name) => (await import(pathToFileURL(join(base, `${name}.js`)).href)).default;

const pairsOf = (dict) => {
  let out = '';
  for (const entry of dict.split('|')) {
    const [from, to] = entry.split(' ');
    if (from && to && [...from].length === 1 && [...to].length === 1 && from !== to) out += from + to;
  }
  return out;
};

const t2s = pairsOf(await load('TSCharacters'));
const jp2t = pairsOf(await load('JPShinjitaiCharacters'));

const src = `/*! Generated by tools/build-hanzi-map.mjs from OpenCC data (Apache-2.0, https://github.com/BYVoid/OpenCC). See vendor/LICENSES.md. */
window.HANZI_MAP = {
  t2s: ${JSON.stringify(t2s)},
  jp2t: ${JSON.stringify(jp2t)}
};
`;
writeFileSync(new URL('../vendor/hanzi-map.js', import.meta.url), src);
console.log(`T2S ${[...t2s].length / 2} pairs, JP2T ${[...jp2t].length / 2} pairs`);
